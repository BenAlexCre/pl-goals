// Phase 8C — creates the three demo pots, then (per-user-batch, see
// writeUserBatch below) adds members, records payments, and writes real
// picks/predictions for both the already-"finished" history gameweeks AND
// the interactive live gameweek (a subset of users only — some people
// haven't picked yet is realistic), and finally settles the history
// gameweeks. All through the exact same validateEntry()/settle() calls
// submit-pick5-picks/submit-lms-pick/submit-predictor-picks/settle-gameweek
// use, so standings, LMS eliminations, jackpot/prize notifications, and
// leaderboards all fall out of the real Game Engine, not hand-written
// demo-only logic. The live gameweek is never settled here — that is
// demo-gameweek-control's job, once its own timeline events bring every
// fixture to 'finished'.
//
// Batched by user, not done in one pass (Slice 1 correction): the local
// Edge Runtime enforces a hard ~2s CPU-time budget per invocation
// (confirmed live — generating 10 users in one call reliably tripped
// "early termination has been triggered" in the container logs). This is
// very likely a real platform constraint, not a local-only quirk, so
// demo-generate-data/index.ts drives this file's functions across multiple
// separate invocations (one per user batch) rather than a single call
// covering every user — see that file's own step dispatcher.

